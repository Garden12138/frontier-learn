import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';

const api = 'http://127.0.0.1:18002/api/v1';
const origin = { Origin: 'http://127.0.0.1:5175' };
const password = 'synthetic browser password 12345';

test('password account, recovery download, OAuth repository selection and cloud guide opt-in', async ({ page }, testInfo) => {
  const identity = `real-${crypto.randomUUID()}`;
  const errors: string[] = [];
  page.on('pageerror', value => errors.push(value.message));
  await page.route('https://github.com/login/oauth/authorize?*', async route => {
    const query = new URL(route.request().url()).searchParams;
    const callback = new URL(query.get('redirect_uri')!);
    callback.searchParams.set('state', query.get('state')!); callback.searchParams.set('code', 'browser-fixture-code');
    await route.fulfill({ status: 302, headers: { Location: callback.toString() }, body: '' });
  });
  await page.goto('/');
  const account = page.getByRole('region', { name: '账号登录' });
  await account.getByRole('button', { name: '创建账号', exact: true }).click();
  await account.getByLabel('用户名', { exact: true }).fill(identity);
  await account.getByLabel('密码', { exact: true }).fill(password);
  await account.getByRole('button', { name: '注册并保存恢复码', exact: true }).click();
  const download = page.waitForEvent('download');
  await account.getByRole('button', { name: '下载恢复文件', exact: true }).click();
  const file = await download;
  const filePath = testInfo.outputPath('recovery-fixture.txt');
  await file.saveAs(filePath);
  const recovery = (await readFile(filePath, 'utf8')).trim().split('\n')[2]!;
  expect(recovery.length).toBeGreaterThan(32);
  expect(await page.locator('body').innerHTML()).not.toContain(recovery);
  await account.getByRole('button', { name: '进入学习空间', exact: true }).click();
  await page.getByRole('button', { name: '知识来源', exact: true }).click();
  const github = page.getByRole('region', { name: 'GitHub App 连接' });
  await github.getByRole('button', { name: '通过 GitHub 授权连接', exact: true }).click();
  await expect(github).toContainText('fixture-learner');
  await github.getByLabel('App 安装位置').selectOption('7');
  await github.getByRole('combobox', { name: '已授权仓库', exact: true }).selectOption('101');
  await github.getByRole('checkbox').check();
  await github.getByRole('button', { name: '连接所选仓库', exact: true }).click();
  const source = page.getByRole('article', { name: '来源 sample/private-notes' });
  await expect(source).toBeVisible();
  await source.getByText('单独授权笔记 PR 写入目录', { exact: true }).click();
  await source.getByRole('checkbox').check();
  await source.getByRole('button', { name: '确认授权 PR 写入目录', exact: true }).click();
  await expect(source).toContainText('写入权限：notes/');
  await source.getByRole('button', { name: '同步笔记', exact: true }).click();
  await expect(source.getByLabel('同步状态')).toContainText('同步完成');
  await page.screenshot({ path: testInfo.outputPath('github-app-connected.png'), fullPage: true });
  await page.getByRole('button', { name: '设置与数据', exact: true }).click();
  await page.getByRole('button', { name: '同意最小片段用于外部模型处理', exact: true }).click();
  await expect(page.getByRole('button', { name: '撤销外部模型处理授权', exact: true })).toBeVisible();
  const analyzed = await page.request.post(`${api}/pages:analyze`, { headers: { ...origin, 'Idempotency-Key': crypto.randomUUID() }, data: { consent: true, cloud_processing_allowed: true,
    page: { title: 'Synthetic Attention source for real adapter', url: 'https://arxiv.org/abs/2410.12345', provider: 'ARXIV', scope: 'ABSTRACT', truncated: false, selection: null,
      blocks: [{ id: 'b0', heading: 'Abstract', selector: 'blockquote', text: 'Attention is discussed in this synthetic excerpt. Its claims require verification.' }] } } });
  expect(analyzed.ok()).toBe(true);
  await page.getByRole('button', { name: '导学会话', exact: true }).click();
  await page.getByRole('button', { name: /Synthetic Attention source for real adapter/ }).click();
  const session = page.getByRole('region', { name: '已保存导学会话' });
  await expect(session).toContainText('模型解释/推测 · 需要核验');
  await session.getByLabel('继续提问').fill('请用一个新例子解释来源的限制。');
  await session.getByRole('checkbox', { name: /允许本次追问/ }).check();
  await session.getByRole('button', { name: '保存追问', exact: true }).click();
  await expect(session.getByText('模型解释/推测 · 需要核验', { exact: true })).toHaveCount(2);
  expect(await page.locator('body').innerHTML()).not.toMatch(/ghu_fixture|ghr_fixture|ghs_fixture|fixture-model-secret/);
  await page.screenshot({ path: testInfo.outputPath('cloud-guide-opt-in.png'), fullPage: true });
  await page.getByRole('button', { name: '退出登录', exact: true }).click();
  const recover = page.getByRole('region', { name: '账号登录' });
  await recover.getByRole('button', { name: '恢复账号', exact: true }).click();
  await recover.getByLabel('用户名', { exact: true }).fill(identity);
  await recover.getByLabel('新密码', { exact: true }).fill(password + ' changed');
  await recover.getByLabel('恢复码', { exact: true }).fill(recovery);
  await recover.getByRole('button', { name: '确认恢复并撤销旧登录', exact: true }).click();
  await expect(recover.getByRole('button', { name: '返回密码登录', exact: true })).toBeDisabled();
  await recover.getByRole('button', { name: '下载恢复文件', exact: true }).click();
  await recover.getByRole('button', { name: '返回密码登录', exact: true }).click();
  await recover.getByLabel('密码', { exact: true }).fill(password + ' changed');
  await recover.getByRole('button', { name: '登录学习空间', exact: true }).click();
  await expect(page.getByRole('button', { name: '设置与数据', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

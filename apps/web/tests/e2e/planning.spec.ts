import { expect, test } from '@playwright/test';

test('new learner without a repository can plan, change history and keep uncertainty', async ({ page }, testInfo) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await page.getByLabel('开发体验账号').fill('planning-browser-user');
  await page.getByRole('button', { name: '进入学习空间' }).click();
  await page.getByRole('button', { name: '设定学习目标' }).click();
  await page.getByLabel('想学会什么').fill('理解园艺中的土壤与浇水');
  await page.getByLabel('当前目标每日可用时间（分钟）').fill('30');
  await page.getByLabel('优先方向（可选，逗号分隔，最多 8 项）').fill('土壤, 浇水');
  await page.getByRole('button', { name: '创建目标', exact: true }).click();
  await page.getByRole('button', { name: '生成学习计划', exact: true }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 1' })).toBeVisible();
  const firstTask = page.getByRole('article', { name: '任务 明确：土壤' });
  await expect(firstTask).toContainText('当前缺少可靠知识证据');
  await expect(firstTask).toContainText('无外部事实依据');
  await page.screenshot({ path: testInfo.outputPath('today.png'), fullPage: true });
  await page.getByRole('button', { name: '采纳整个计划' }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 2' })).toBeVisible();
  await firstTask.getByRole('button', { name: '跳过任务' }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 3' })).toBeVisible();
  await page.getByRole('button', { name: '暂停计划', exact: true }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 4' })).toBeVisible();
  await expect(page.getByRole('button', { name: '恢复计划', exact: true })).toBeVisible();
  await page.getByRole('button', { name: '查看计划历史', exact: true }).click();
  await page.getByRole('button', { name: '查看版本 1', exact: true }).click();
  await expect(page.getByRole('heading', { name: '历史版本 1（只读）' })).toBeVisible();
  await page.getByRole('button', { name: '恢复版本 1（追加修订）', exact: true }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 5' })).toBeVisible();
  await page.getByText('插入临时兴趣内容', { exact: true }).click();
  await page.getByLabel('兴趣内容', { exact: true }).fill('观察盆栽');
  await page.getByLabel('建议投入分钟', { exact: true }).fill('5');
  await page.getByRole('button', { name: '插入计划', exact: true }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 6' })).toBeVisible();
  const interest = page.getByRole('article', { name: '任务 观察盆栽' });
  await interest.getByRole('button', { name: '标记任务完成' }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 7' })).toBeVisible();
  await page.screenshot({ path: testInfo.outputPath('history.png'), fullPage: true });
  await page.getByRole('button', { name: '知识画像', exact: true }).click();
  await expect(page.getByText('还没有对应的知识证据。', { exact: false })).toBeVisible();
  await page.getByRole('button', { name: '今日学习', exact: true }).click();
  await page.reload();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 7' })).toBeVisible();
  await page.getByRole('button', { name: '学习目标', exact: true }).click();
  await page.getByRole('button', { name: '编辑目标', exact: true }).click();
  await page.getByLabel('当前目标每日可用时间（分钟）').fill('15');
  await page.getByRole('button', { name: '保存目标', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('目标已修改');
  await page.getByRole('button', { name: '根据最新证据重新规划' }).click();
  await expect(page.getByRole('heading', { name: '当前计划 · 版本 8' })).toBeVisible();
  expect(errors).toEqual([]);
});

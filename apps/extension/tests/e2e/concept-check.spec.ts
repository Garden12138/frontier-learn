import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { expect, test } from '@playwright/test';

test('MV3 concept check: failure, cancellation, new jobs, private rubric, answer and shared draft', async ({ playwright, request }, info) => {
  const identity = `concept-${crypto.randomUUID()}`;
  const login = await request.post('http://127.0.0.1:18002/api/v1/auth/mock-login', { data: { identity, client: 'extension' } });
  const headers = { Authorization: `Bearer ${(await login.json()).access_token as string}` };
  const settings = await (await request.get('http://127.0.0.1:18002/api/v1/settings', { headers })).json() as { version: number };
  expect((await request.put('http://127.0.0.1:18002/api/v1/settings', { headers, data: { version: settings.version, cloud_processing_allowed: true, confirm: true } })).ok()).toBe(true);
  const profile = await mkdtemp(path.join(tmpdir(), 'frontier-concept-'));
  const context = await playwright.chromium.launchPersistentContext(profile, { channel: 'chromium', headless: true,
    args: [`--disable-extensions-except=${path.resolve('apps/extension/.output/chrome-mv3')}`, `--load-extension=${path.resolve('apps/extension/.output/chrome-mv3')}`] });
  try {
    const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
    const panel = await context.newPage();
    await panel.goto(`chrome-extension://${new URL(worker.url()).host}/sidepanel.html`);
    await panel.getByLabel('开发体验账号').fill(identity);
    await panel.getByRole('button', { name: '连接体验账号', exact: true }).click();
    await panel.getByText('使用手工粘贴文本', { exact: true }).click();
    await panel.getByLabel('学习材料', { exact: true }).fill('TRIAL_FAIL_ONCE · Self-Attention 根据注意力权重组合输入向量，得到上下文向量。此处是固定的 Fake 模型浏览器验收材料，不证明真人理解。');
    await panel.getByRole('button', { name: '预览粘贴材料' }).click();
    const save = panel.getByRole('region', { name: '保存并开启导学' });
    await save.getByRole('checkbox').first().check();
    await save.getByRole('button', { name: '保存并开启导学', exact: true }).click();
    const session = panel.getByRole('region', { name: '已保存导学会话' });
    await expect(session).toContainText('本地规则建议');
    const quiz = session.getByRole('region', { name: '理解验证' });
    await quiz.getByLabel('拟题章节').selectOption('b0');
    await quiz.getByRole('checkbox').check();
    await quiz.getByRole('button', { name: '生成概念选择题', exact: true }).click();
    await expect(quiz).toContainText('FAILED');
    await expect(quiz).toContainText('MODEL_UNAVAILABLE');
    await quiz.getByRole('checkbox').check();
    await quiz.getByRole('button', { name: '恢复概念拟题（新任务）', exact: true }).click();
    await quiz.getByRole('button', { name: '取消概念拟题', exact: true }).click();
    await expect(quiz).toContainText('CANCELLED');
    await quiz.getByRole('checkbox').check();
    await quiz.getByRole('button', { name: '恢复概念拟题（新任务）', exact: true }).click();
    await expect(quiz).toContainText('SUCCEEDED');
    await expect(quiz).not.toContainText('评分提示：选择 C');
    const sessions = await (await request.get('http://127.0.0.1:18002/api/v1/sessions', { headers })).json() as { id: string }[];
    const list = await request.get(`http://127.0.0.1:18002/api/v1/assessments?session_id=${sessions[0]!.id}`, { headers });
    expect(await list.text()).not.toContain('评分提示：选择 C');
    expect(await list.text()).not.toContain('correct_choice');
    await quiz.getByRole('radio', { name: /^C ·/ }).check();
    await quiz.getByRole('button', { name: '提交作答', exact: true }).click();
    await expect(quiz).toContainText('作答后评分说明');
    await expect(quiz).toContainText('评分提示：选择 C');
    await quiz.getByRole('button', { name: '确认评价并加入学习证据', exact: true }).click();
    await expect(quiz).toContainText('已确认低强度证据');
    await quiz.getByRole('button', { name: '生成笔记草稿', exact: true }).click();
    await expect(quiz).toContainText('草稿已保存');
    const downloaded = panel.waitForEvent('download');
    await quiz.getByRole('button', { name: '下载 Markdown，仅本地保存', exact: true }).click();
    expect((await downloaded).suggestedFilename()).toMatch(/^learning-.*\.md$/);
    const web = await context.newPage();
    await web.goto('http://127.0.0.1:5175');
    await web.getByLabel('开发体验账号').fill(identity);
    await web.getByRole('button', { name: '进入学习空间', exact: true }).click();
    await web.getByRole('button', { name: '导学会话', exact: true }).click();
    await web.getByRole('button', { name: /^手工粘贴材料 ·/ }).click();
    await expect(web.getByRole('region', { name: '理解验证' })).toContainText('评分提示：选择 C');
    await panel.screenshot({ path: info.outputPath('concept-confirmed.png'), fullPage: true });
    await panel.reload();
    await panel.getByText('继续已保存的会话', { exact: true }).click();
    await panel.getByRole('button', { name: '手工粘贴材料', exact: true }).click();
    await expect(panel.getByRole('region', { name: '理解验证' })).toContainText('已确认低强度证据');
  } finally { await context.close(); await rm(profile, { recursive: true, force: true }); }
});
